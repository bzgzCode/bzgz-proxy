-- Bzgz Proxy — D1 schema (safe to re-run)
CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL DEFAULT 'User',
  joined INTEGER NOT NULL DEFAULT 0,
  last INTEGER NOT NULL DEFAULT 0,
  lang TEXT,
  state TEXT,
  banned INTEGER NOT NULL DEFAULT 0,
  notify INTEGER NOT NULL DEFAULT 1,
  jchk INTEGER NOT NULL DEFAULT 0,
  extra TEXT
);
CREATE TABLE IF NOT EXISTS proxies (
  id TEXT PRIMARY KEY,
  uid INTEGER NOT NULL,
  name TEXT NOT NULL,
  url TEXT NOT NULL,
  enter TEXT NOT NULL,
  secret TEXT NOT NULL,
  created INTEGER NOT NULL,
  fail INTEGER NOT NULL DEFAULT 0,
  seen INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_proxies_uid ON proxies(uid);
CREATE TABLE IF NOT EXISTS usage (
  pid TEXT NOT NULL,
  day TEXT NOT NULL,
  req INTEGER NOT NULL DEFAULT 0,
  bytes INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (pid, day)
);
CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT);
CREATE TABLE IF NOT EXISTS admins (id INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS channels (id TEXT PRIMARY KEY, title TEXT);
CREATE TABLE IF NOT EXISTS tickets (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  uid INTEGER NOT NULL,
  subject TEXT,
  status TEXT NOT NULL DEFAULT 'open',
  created INTEGER NOT NULL,
  upd INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_tickets_uid ON tickets(uid);
CREATE TABLE IF NOT EXISTS msgs (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  tid INTEGER NOT NULL,
  admin INTEGER NOT NULL DEFAULT 0,
  text TEXT,
  ts INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_msgs_tid ON msgs(tid);
